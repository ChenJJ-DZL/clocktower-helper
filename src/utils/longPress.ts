/**
 * 触屏长按（用于在没有右键的设备上打开座位菜单）的全局阈值。
 *
 * 需求：手指按住 ≥1000ms 即**立即弹出**右键菜单，无需松开；
 * 松开时不得顺带把座位「选中」（长按弹出的菜单与此前的点击选中互斥）。
 *
 * 历史上圆桌座位（SeatNode）没有自己的定时器，依赖浏览器原生的 long-press 合成
 * contextmenu，时机由浏览器决定（实测表现为「松开才弹」）；矩阵视图（SeatGrid）
 * 则有 500ms 定时器，两者不一致。这里统一成一个常量，两处共用。
 */
export const LONG_PRESS_MS = 1000;

/** 长按过程中手指位移超过该像素数即取消长按（视为滑动/拖动，不应弹菜单）。 */
export const LONG_PRESS_MOVE_TOLERANCE_PX = 12;

/**
 * 触屏手势归属的尘埃阈值：位移一旦 ≥ 该值就判定为「拖拽换位」，
 * 立即取消长按菜单定时器，改走拖拽路径（iOS 桌面图标的标准解法：位移决定手势归属）。
 * 小于该值则仍按长按处理 —— 按住不动满 LONG_PRESS_MS 照常弹出菜单。
 */
export const DRAG_START_THRESHOLD_PX = 8;
